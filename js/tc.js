const TC_MAP = {};
TC_PAIRS.split(/\s+/).forEach(function (pair) {
  if (pair.length >= 2) TC_MAP[pair[0]] = pair.slice(1);
});

/* 词级修正：先做单字映射，再把被误转的多字词还原为正确繁体 */
const TC_WORD_FIXES = [
  [/係列/g, "系列"], // 系列（丛书义）保持"系"
  [/係統/g, "系統"], // 系统
  [/北鬥/g, "北斗"], // 北斗卫星系统，"斗"不转"鬥"
];

/* 历的多音处理：日期义的"历"→"曆"（万历/日历），其余→"歷"（历史/经历） */
function convertLi(text) {
  return text
    .replace(/万历/g, "万厤") // 临时占位，避免被通用映射覆盖
    .replace(/日历/g, "日厤")
    .replace(/历/g, "歷")
    .replace(/厤/g, "曆");
}

function toTraditional(text) {
  if (!text) return text;
  const src = convertLi(text);
  let out = "";
  for (const ch of src) {
    out += TC_MAP[ch] || ch;
  }
  for (const [pattern, replacement] of TC_WORD_FIXES) {
    out = out.replace(pattern, replacement);
  }
  return out;
}
